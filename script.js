const revealItems = document.querySelectorAll("[data-reveal]");
const intro = document.querySelector(".site-intro");
const skipIntro = document.querySelector(".intro-skip");
const typedCode = document.getElementById("typed-code");
const languageButtons = document.querySelectorAll("[data-lang]");

if (intro) {
  document.body.classList.add("intro-active");
}

function setLanguage(language) {
  const selected = translations[language] ? language : "en";
  const copy = translations[selected];

  document.documentElement.lang = selected;
  localStorage.setItem("panta-studio-language", selected);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (copy[key]) {
      element.innerHTML = copy[key];
    }
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === selected;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
}

function typeHeroCode() {
  if (!typedCode || typedCode.dataset.started === "true") return;

  const code = typedCode.dataset.code || "";
  const duration = 3000;
  const delay = Math.max(18, Math.floor(duration / Math.max(code.length, 1)));
  let index = 0;

  typedCode.dataset.started = "true";
  typedCode.textContent = "";

  const timer = window.setInterval(() => {
    typedCode.textContent = code.slice(0, index + 1);
    index += 1;

    if (index >= code.length) {
      window.clearInterval(timer);
    }
  }, delay);
}

function finishIntro() {
  if (!intro || intro.classList.contains("is-hidden")) return;
  intro.classList.add("is-hidden");
  document.body.classList.remove("intro-active");
  typeHeroCode();
}

const savedLanguage = localStorage.getItem("panta-studio-language") || "en";
setLanguage(savedLanguage);

const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        revealObserver.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.14 }
);

revealItems.forEach((item) => revealObserver.observe(item));

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

if (intro) {
  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    finishIntro();
  } else {
    window.setTimeout(finishIntro, 2350);
    intro.addEventListener("click", finishIntro);
  }
} else {
  typeHeroCode();
}

if (skipIntro) {
  skipIntro.addEventListener("click", (event) => {
    event.stopPropagation();
    finishIntro();
  });
}

window.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    finishIntro();
  }
});

document.querySelectorAll('a[href^="#"]').forEach((link) => {
  link.addEventListener("click", (event) => {
    const target = document.querySelector(link.getAttribute("href"));
    if (!target) return;

    event.preventDefault();
    target.scrollIntoView({ behavior: "smooth", block: "start" });
  });
});
