function setLanguage(language) {
  const selected = translations[language] ? language : "en";
  const copy = translations[selected];
  window.PantaHomeI18n?.apply(selected);

  document.documentElement.lang = selected;
  localStorage.setItem("panta-studio-language", selected);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (copy[key]) {
      element.innerHTML = copy[key];
    }
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === selected;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
}

function typeHeroCode() {
  if (!typedCode || typedCode.dataset.started === "true") return;

  const code = typedCode.dataset.code || "";
  const duration = 3000;
  const delay = Math.max(18, Math.floor(duration / Math.max(code.length, 1)));
  let index = 0;

  typedCode.dataset.started = "true";
  typedCode.textContent = "";

  const timer = window.setInterval(() => {
    typedCode.textContent = code.slice(0, index + 1);
    index += 1;

    if (index >= code.length) {
      window.clearInterval(timer);
    }
  }, delay);
}

